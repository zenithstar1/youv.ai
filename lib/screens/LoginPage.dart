class UnderlineTextField extends StatefulWidget {
  final TextEditingController controller;
  final TextInputType keyboardType;
  final double inputHeight;
  final String? prefixText;
  final bool isPhone;

  const UnderlineTextField({
    super.key,
    required this.controller,
    required this.keyboardType,
    required this.inputHeight,
    this.prefixText,
    this.isPhone = false,
  });

  @override
  State<UnderlineTextField> createState() => _UnderlineTextFieldState();
}

class _UnderlineTextFieldState extends State<UnderlineTextField> with SingleTickerProviderStateMixin {
  late FocusNode _focusNode;
  late AnimationController _animController;
  late Animation<double> _underlineAnim;

  @override
  void initState() {
    super.initState();
    _focusNode = FocusNode();
    _animController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 220),
    );
    _underlineAnim = Tween<double>(begin: 0, end: 1).animate(
      CurvedAnimation(parent: _animController, curve: Curves.easeOut),
    );
    _focusNode.addListener(() {
      if (_focusNode.hasFocus) {
        _animController.forward();
      } else {
        _animController.reverse();
      }
    });
  }

  @override
  void dispose() {
    _focusNode.dispose();
    _animController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return LayoutBuilder(
      builder: (context, constraints) {
        final W = constraints.maxWidth;
        return Column(
          children: [
            SizedBox(
              height: widget.inputHeight,
              child: TextField(
                controller: widget.controller,
                focusNode: _focusNode,
                keyboardType: widget.keyboardType,
                style: TextStyle(
                  fontSize: W * 0.040,
                  color: Colors.black87,
                  fontWeight: FontWeight.w400,
                ),
                decoration: InputDecoration(
                  isDense: true,
                  border: InputBorder.none,
                  prefixText: widget.prefixText,
                  prefixStyle: TextStyle(
                    fontSize: W * 0.040,
                    color: Colors.black87,
                    fontWeight: FontWeight.w400,
                  ),
                  contentPadding: EdgeInsets.zero,
                ),
                cursorColor: const Color(0xFFE8B4BA),
                textInputAction: TextInputAction.next,
                inputFormatters: widget.isPhone
                    ? [
                        // Only allow numbers after +91
                      ]
                    : null,
              ),
            ),
            AnimatedBuilder(
              animation: _underlineAnim,
              builder: (context, child) {
                return Align(
                  alignment: Alignment.centerLeft,
                  child: Container(
                    height: 2,
                    width: W * 0.88 * _underlineAnim.value,
                    decoration: BoxDecoration(
                      color: _focusNode.hasFocus ? const Color(0xFFE8B4BA) : const Color(0xFFB0B0B0).withOpacity(0.4),
                      borderRadius: BorderRadius.circular(2),
                    ),
                  ),
                );
              },
            ),
          ],
        );
      },
    );
  }
}

