class OTPVerificationScreen extends StatefulWidget {
  final String phone;
  final String name;
  final String city;

  const OTPVerificationScreen({
    super.key,
    required this.phone,
    required this.name,
    required this.city,
  });

  @override
  State<OTPVerificationScreen> createState() => _OTPVerificationScreenState();
}

class _OTPVerificationScreenState extends State<OTPVerificationScreen> {
  final List<TextEditingController> _otpControllers = List.generate(6, (_) => TextEditingController());
  bool _loading = false;
  String _error = '';
  int _timer = 30;

  @override
  void initState() {
    super.initState();
    _startTimer();
  }

  void _startTimer() {
    Future.delayed(const Duration(seconds: 1), () {
      if (_timer > 0 && mounted) {
        setState(() => _timer--);
        _startTimer();
      }
    });
  }

  void _verifyOtp() {
    final otp = _otpControllers.map((c) => c.text).join();
    if (otp.length != 6) {
      setState(() => _error = 'Please enter the 6-digit OTP');
      return;
    }

    setState(() { _loading = true; });
    context.read<AuthBloc>().add(
      VerifyLoginMobile(
        phone: widget.phone,
        name: widget.name,
        email: '',
        password: '',
        otp: otp,
      ),
    );
  }

  void _resendCode() {
    setState(() { _timer = 30; });
    _startTimer();
    context.read<AuthBloc>().add(
      SendOtpRequested(phone: widget.phone, flow: 'signup'),
    );
  }

  @override
  Widget build(BuildContext context) {
    final W = MediaQuery.of(context).size.width;
    return BlocListener<AuthBloc, AuthState>(
      listener: (context, state) {
        if (state is AuthLoading) {
          setState(() {
            _loading = true;
            _error = '';
          });
        } else if (state is AuthAuthenticated) {
          setState(() => _loading = false);
          Navigator.pushReplacement(
            context,
            MaterialPageRoute(builder: (_) => AnalysisTypeScreen()),
          );
        } else if (state is AuthMessage) {
          setState(() => _loading = false);
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text(state.message)),
          );
        } else if (state is AuthError) {
          setState(() {
            _loading = false;
            _error = state.error;
          });
        }
      },
      child: Scaffold(
        backgroundColor: const Color(0xFFF9F0EC),
        body: SafeArea(
        child: Padding(
          padding: EdgeInsets.symmetric(horizontal: W * 0.07, vertical: 40),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              SizedBox(height: 30),
              Text('Verify Your Number',
                style: GoogleFonts.poppins(
                  fontSize: W * 0.06,
                  fontWeight: FontWeight.w700,
                  color: Colors.black87,
                ),
              ),
              SizedBox(height: 12),
              Text('Enter the 6-digit code sent to +91 ${widget.phone}',
                style: GoogleFonts.poppins(
                  fontSize: W * 0.035,
                  color: Colors.black54,
                ),
              ),
              SizedBox(height: 32),
              Center(
                child: Wrap(
                  spacing: 8,
                  runSpacing: 8,
                  alignment: WrapAlignment.center,
                  children: List.generate(6, (i) => _buildOtpBox(i)),
                ),
              ),
              if (_error.isNotEmpty)
                Padding(
                  padding: const EdgeInsets.only(top: 12),
                  child: Text(_error, style: const TextStyle(color: Colors.red)),
                ),
              SizedBox(height: 32),
              Row(
                children: [
                  TextButton(
                    onPressed: _timer == 0 ? _resendCode : null,
                    child: Text(
                      _timer == 0 ? 'Resend Code' : 'Resend in $_timer s',
                      style: GoogleFonts.poppins(
                        fontSize: W * 0.032,
                        color: Colors.black,
                      ),
                    ),
                  ),
                ],
              ),
              SizedBox(height: 32),
              SizedBox(
                width: double.infinity,
                height: 52,
                child: ElevatedButton(
                  onPressed: !_loading ? _verifyOtp : null,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: const Color(0xFFE4B3B8),
                    foregroundColor: Colors.black87,
                    elevation: 4,
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(24)),
                  ),
                  child: _loading
                      ? const CircularProgressIndicator()
                      : Text('Verify & Start Scan',
                          style: GoogleFonts.poppins(
                            fontSize: W * 0.045,
                            fontWeight: FontWeight.w600,
                          ),
                        ),
                ),
              ),
            ],
          ),
        ),
        ),
      ),
    );
  }

  Widget _buildOtpBox(int i) {
    return SizedBox(
      width: 44,
      child: TextField(
        controller: _otpControllers[i],
        keyboardType: TextInputType.number,
        maxLength: 1,
        textAlign: TextAlign.center,
        style: GoogleFonts.poppins(fontSize: 20, fontWeight: FontWeight.w600),
        decoration: InputDecoration(
          counterText: '',
          isDense: true,
          contentPadding: const EdgeInsets.symmetric(vertical: 14),
          filled: true,
          fillColor: Colors.white,
          border: OutlineInputBorder(
            borderRadius: BorderRadius.circular(10),
            borderSide: const BorderSide(color: Color(0xFFE6E2DD)),
          ),
          focusedBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(10),
            borderSide: const BorderSide(color: Color(0xFF6B3A3A), width: 1.8),
          ),
          enabledBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(10),
            borderSide: const BorderSide(color: Color(0xFFE6E2DD)),
          ),
        ),
        onChanged: (v) {
          if (v.isNotEmpty && i < 5) {
            FocusScope.of(context).nextFocus();
          } else if (v.isEmpty && i > 0) {
            FocusScope.of(context).previousFocus();
          }
          if (_otpControllers.every((c) => c.text.isNotEmpty)) {
            _verifyOtp();
          }
        },
      ),
    );
  }
